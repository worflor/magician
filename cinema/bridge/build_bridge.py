"""Stage the Panorama bridge into the cinema_dev addon (dev only).

    python -I build_bridge.py [--shots DIR]      then: magician build cinema_dev <out>\\pak90_dir.vpk

Writes, under cinema/addon/panorama/ (git-ignored: the layouts are derived from Valve's):
  layout/replay/citadel_hud_replay.vxml   Valve's replay HUD (part of every HUD: demo playback on any map), plus two
                                     script includes
  layout/hud_hero_testing.vxml       Valve's Testing Tools layout (the Hero Sandbox, live), plus the same includes
  scripts/cinema/cinema_bridge.js    bridge/cinema_bridge.js (compiled to .vjs_c)
  scripts/cinema/cinema_paths.js    every shot in cinema/shots/*.json, then the realtime shots of the scenes being
                                     built (bridge/scene_paths.json, from film.py build), as sample tables
                                     (CINEMA_PATHS) the bridge plays one camera command per rendered frame

The Testing Tools panel exists only in the Hero Sandbox; the replay HUD plays in every demo (dl_midtown included).
Where both load, the bridge's root-panel flag keeps one copy. Re-run after a game update (the layouts are re-derived
from the installed pak01) and after editing a shot.
"""
import glob
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CINEMA = os.path.dirname(HERE)
ADDON = os.path.join(CINEMA, "addon")
sys.path.insert(0, CINEMA)
import shoot  # noqa: E402
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "ingame"))
import gamepaths  # noqa: E402  (locations as magician.exe resolves them)

CLI = gamepaths.vrf()
PAK = os.path.join(gamepaths.try_game(), "citadel", "pak01_dir.vpk")
LAYOUTS = ["panorama/layout/replay/citadel_hud_replay.vxml_c", "panorama/layout/hud_hero_testing.vxml_c"]
INCLUDES = ('\t<scripts>\n'
            '\t\t<include src="file://{resources}/scripts/cinema/cinema_paths.js" />\n'
            '\t\t<include src="file://{resources}/scripts/cinema/cinema_bridge.js" />\n'
            '\t</scripts>\n')
SAMPLE_FPS = 30


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:   # no BOM (resourcecompiler rejects one)
        f.write(text)


def layout(compiled):
    rel = compiled[:-len(".vxml_c")]   # panorama/layout/...
    tmp = tempfile.mkdtemp(prefix="cinema_bridge_")
    try:   # decompile outside the addon: Source 2 Viewer may drop files beside its input
        subprocess.run([CLI, "-i", PAK, "--vpk_filepath", compiled, "-d", "-o", tmp], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        text = open(os.path.join(tmp, *(rel + ".xml").split("/")), encoding="utf-8").read()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    text = "\n".join(l for l in text.splitlines() if not l.startswith("<!-- xml reconstructed")) + "\n"
    if "</styles>" not in text or "<scripts>" in text:
        sys.exit(f"{rel}: no <styles> block, or scripts of its own: Valve changed it, look before patching")
    text = text.replace("</styles>\n", "</styles>\n" + INCLUDES, 1)
    write(os.path.join(ADDON, *(rel + ".vxml").split("/")), text)


def paths(shots_dir):
    out = []
    for fn in sorted(glob.glob(os.path.join(shots_dir, "*.json"))):
        shot = json.load(open(fn, encoding="utf-8"))
        if shot.get("camera", "spec") != "spec":
            continue
        s = dict(shot, fps=SAMPLE_FPS)
        samples = []
        for k, pos, pitch, yaw in shoot.frames(s):
            samples.append([round(pos[0], 2), round(pos[1], 2), round(pos[2] - shot.get("spec_eye", shoot.SPEC_EYE), 2),
                            round(pitch, 3), round(yaw, 3)])
        out.append({"name": shot["name"], "mode": "spec", "fps": SAMPLE_FPS, "seconds": shot.get("seconds", 10),
                    "samples": samples})
    # the realtime shots of the scenes being built (film.py build writes them): played one camera per rendered frame
    scene_paths = os.path.join(HERE, "scene_paths.json")
    if os.path.exists(scene_paths):
        out += json.load(open(scene_paths, encoding="utf-8"))
    body = json.dumps(out, separators=(",", ":"))
    write(os.path.join(ADDON, "panorama", "scripts", "cinema", "cinema_paths.js"),
          '"use strict";\n// generated by cinema/bridge/build_bridge.py from cinema/shots/*.json\nvar CINEMA_PATHS = ' + body + ";\n")
    return [p["name"] for p in out]


def main(a):
    shots_dir = a[a.index("--shots") + 1] if "--shots" in a else os.path.join(CINEMA, "shots")
    for compiled in LAYOUTS:
        layout(compiled)
    names = paths(shots_dir)
    shutil.copyfile(os.path.join(HERE, "cinema_bridge.js"), os.path.join(ADDON, "panorama", "scripts", "cinema", "cinema_bridge.js"))
    print(f"bridge staged: layout, bridge, {len(names)} path(s): {', '.join(names)}")


if __name__ == "__main__":
    main(sys.argv[1:])
