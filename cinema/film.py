"""Film a scene: from a scene file (the shot language, scene.py) to an edit-ready video, in the retail game.

    python -I film.py check  <scene.toml>                 # parse, resolve every frame, list the shots, warn
    python -I film.py plan   <scene.toml> [--png out.png] # dry run: a top-down plan of every camera path and actor
    python -I film.py animatic <scene.toml> [--size 640x360]  # dry run: the timing and framing as a video, no game
    python -I film.py photomatic <scene.toml> [--size 1280x720]  # the animatic from a stills pass: real frames, held
    python -I film.py build  <scene.toml> [...]           # write the alias chains into the pak and build pak90
    python -I film.py render <scene.toml> [--shots a,b] [--stills N] [--route keys|console]
    python -I film.py encode <scene.toml> [--keep-frames] # shots -> master.mkv (FFV1, lossless) + preview.mp4 (x264); frames removed
    python -I film.py lossy  <scene.toml>                 # preview.mp4 and phone.mp4 again from master.mkv
    python -I film.py make   <scene.toml> [...]           # check, build, render, encode: one command, shot file to video

Output: <reference>\\work\\cinema\\films\\<scene>\\ (CINEMA_WORK moves it) (shots\\<shot>\\f00000.png, master.mkv,
preview.mp4, render.log). `--stills N` renders N frames spread over each shot instead of every frame (framing check).

How a frame is made (lockstep, the default; proven 2026-11-21, build 6864): the demo is paused; each frame is one
alias of a chain baked into the cinema pak (`cfg/cinema/<scene>_<shot>.cfg`): `demo_step_tick N` (advance N whole
ticks, then pause again) and `spec_goto x y z pitch yaw`. A key bound to `cin_next` runs the next alias: one key tap a
frame, nothing typed into the game while a shot renders. After a settle time the window is captured (PrintWindow).
About 0.26 s a frame. Realtime shots (slower than one tick a frame) play the demo at `demo_timescale` and tap the
chain at the frame rate while record.py captures the screen; their frames are cut from that recording.

Everything typed goes through console.py, which types with Right Shift: Left Shift is the spectator's Fly Up in a demo
and every underscore typed with it kicked the camera into the sky (the old "drift").
"""
