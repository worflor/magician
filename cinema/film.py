    fin = float(card.get("fade_in", 0.35))
    fout = float(card.get("fade_out", 0.35))
    alpha = (f"alpha='if(lt(t,{fin}),t/{fin},if(gt(t,{length - fout}),max(0,({length}-t)/{fout}),1))'"
             if fin > 0 or fout > 0 else "alpha=1")
