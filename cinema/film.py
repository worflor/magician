class FrameLines:
    """The bridge's "cinema_bridge: frame <k> <name>" lines with the time each was first seen, from a thread that
    polls console.log every 2 ms (a paced render times its captures from them)."""

    def __init__(self, offset, name):
        import console
        import re
        self.path, self.off = console.LOG, offset
        self.pat = re.compile(r"cinema_bridge: frame (\d+) " + re.escape(name) + r"\b")
        self.seen = {}
        self.stop = False
        self.lock = threading.Lock()
        self.t = threading.Thread(target=self._run, daemon=True)
        self.t.start()

    def _run(self):
        buf = ""
        while not self.stop:
            with open(self.path, "rb") as f:
                f.seek(self.off)
                chunk = f.read()
            now = time.perf_counter()
            if chunk:
                self.off += len(chunk)
                buf += chunk.decode("utf-8", "replace")
                lines = buf.split("\n")
                buf = lines.pop()
                with self.lock:
                    for line in lines:
                        m = self.pat.search(line)
                        if m:
                            self.seen.setdefault(int(m.group(1)), now)
            time.sleep(0.002)

    def arrived(self, k):
        with self.lock:
            return self.seen.get(k)

    def wait(self, k, timeout):
        end = time.perf_counter() + timeout
        while time.perf_counter() < end:
            v = self.arrived(k)
            if v is not None:
                return v
            time.sleep(0.002)
        return None

    def period(self):
        """The median gap between consecutive frame lines so far (None until there are a few)."""
        with self.lock:
            ks = sorted(self.seen)
            gaps = [self.seen[b] - self.seen[a] for a, b in zip(ks, ks[1:]) if b == a + 1]
        if len(gaps) < 3:
            return None
        gaps.sort()
        return gaps[len(gaps) // 2]

    def close(self):
        self.stop = True
        self.t.join(1.0)


class FrameSink:
    """Captured frames (BGRA, as capture.grab returns them) straight into a lossless FFV1 file through ffmpeg's
    stdin. A writer thread keeps the capture loop from waiting on the encoder."""

    def __init__(self, path, w, h, fps):
        import queue
        self.path, self.n = path, 0
        self.p = subprocess.Popen(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "bgra",
                                   "-s", f"{w}x{h}", "-r", str(fps), "-i", "-", "-c:v", "ffv1", "-level", "3", "-slices", "16",
                                   "-pix_fmt", "bgr0", path], stdin=subprocess.PIPE)
        self.q = queue.Queue(maxsize=16)
        self.err = None
        self.t = threading.Thread(target=self._run, daemon=True)
        self.t.start()

    def _run(self):
        while True:
            px = self.q.get()
            if px is None:
                return
            try:
                self.p.stdin.write(px)
            except OSError as e:
                self.err = e
                return

    def write(self, px):
        if self.err:
            raise RuntimeError(f"ffmpeg stopped taking frames for {self.path}: {self.err}")
        self.q.put(px)
        self.n += 1

    def close(self):
        self.q.put(None)
        self.t.join()
        self.p.stdin.close()
        if self.p.wait() != 0 or self.err:
            raise RuntimeError(f"ffmpeg failed writing {self.path} ({self.err or 'exit ' + str(self.p.returncode)})")


def jumps(path, w=320, h=180):
    """Frames that jump away and snap back (a cloth solver seeing a teleport: Maid Lash's skirt stretched metres for
    one or two frames, 2026-11-21): frame k (or the pair k, k+1) differs from both neighbours far more than the
    neighbours differ from each other. Measured on the whole frame and on its centre (where the actors are).
    Returns [(frame, how many frames, strength)]."""
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-vf", f"scale={w}:{h}", "-f", "rawvideo", "-pix_fmt",
                          "gray", "-"], capture_output=True).stdout
    n = len(raw) // (w * h)
    if n < 4:
        return []
    frames = [raw[i * w * h:(i + 1) * w * h] for i in range(n)]
    cx0, cx1, cy0, cy1 = w // 4, 3 * w // 4, h // 6, 5 * h // 6
    centre = [b"".join(f[y * w + cx0:y * w + cx1] for y in range(cy0, cy1)) for f in frames]

    def d(a, b):
        return sum(abs(x - y) for x, y in zip(a[::3], b[::3])) / (len(a[::3]) or 1)

    out = []
    for imgs in (frames, centre):
        for k in range(1, n - 1):
            for span in (1, 2):
                if k + span >= n:
                    continue
                away = min(d(imgs[k - 1], imgs[k]), d(imgs[k + span - 1], imgs[k + span]))
                base = d(imgs[k - 1], imgs[k + span])
                if away > 4.0 and away > 4.0 * max(base, 0.3):
                    out.append((k, span, round(away / max(base, 0.3), 1)))
    seen, res = set(), []
    for k, span, s in sorted(out):
        if k not in seen:
            seen.update(range(k, k + span))
            res.append((k, span, s))
    return res


def _flat(px, w, h):
    """Nearly one colour (the camera inside a wall or under the floor): sample 400 pixels, check the spread."""
    vals = []
    for j in range(20):
        for i in range(20):
            o = ((h * (j * 2 + 1) // 40) * w + w * (i * 2 + 1) // 40) * 4
            vals.append(px[o] + px[o + 1] + px[o + 2])
    m = sum(vals) / len(vals)
    return (sum((v - m) ** 2 for v in vals) / len(vals)) ** 0.5 < 12


def _first_cut(rec):
    """Seconds into the recording of the first big picture change (the slate -> frame 0 jump)."""
    r = subprocess.run(["ffmpeg", "-hide_banner", "-i", rec, "-vf", "select='gt(scene,0.25)',showinfo", "-f", "null", "-"],
                       capture_output=True, text=True)
    for line in r.stderr.splitlines():
        if "pts_time:" in line:
            return float(line.split("pts_time:")[1].split()[0])
    raise RuntimeError(f"{rec}: no cut from the slate found (did the chain run?)")


def render(scene, only=None, stills=0, session=None, route="keys"):
    from session import Session
    dest = out_dir(scene)
    os.makedirs(dest, exist_ok=True)
    log = open(os.path.join(dest, "render.log"), "a", encoding="utf-8")
    shots = [s for s in scene.all_shots() if (not only or s.name in only) and s.card is None]
    planned = sorted({s.take_key for s in shots if scene.planned(s.take_key)})
    if planned:
        raise RuntimeError(f"{scene.name}: take(s) {', '.join(planned)} are the [blocking] plan, not a SourceTV take: "
                           "stage and record the take, then name it in [scene] take / [takes]")

    def play(s, r, key):
        take = scene.take_path(key)
        rel = os.path.relpath(take, os.path.join(os.path.dirname(os.path.dirname(take)))).replace("\\", "/")
        r.say(f"take {key}: playdemo {rel}")
        r.restore()
        r.at_tick = None
        off = s.log_offset()
        r.cmd(f"playdemo {rel}", 0.5)
        # "Host activate: Playing Demo" comes when the demo really runs, after its resources load (40 s on a cold
        # start); "[Demo] playing demo from" comes at once. A pause or seek before activation crashed the client
        # (FATAL ERROR: CopyNewEntity: invalid class index, 2026-11-21): wait for the activation, then a little more.
        if not s.wait_log("Host activate: Playing Demo", 240, offset=off):
            raise RuntimeError(f"the demo {rel} did not start within 240 s")
        time.sleep(6)

    def body(s):
        r = Renderer(s, scene, log)
        r.say(f"render {scene.name}: {len(shots)} shot(s){' (stills)' if stills else ''}")
        playing = None
        try:
            for shot in shots:
                if shot.take_key != playing:   # each take is played when its shots come up
                    play(s, r, shot.take_key)
                    playing = shot.take_key
                sdir = os.path.join(dest, "shots", shot.name + ("_stills" if stills else ""))
                if os.path.isdir(sdir):
                    shutil.rmtree(sdir)
                mode = "lockstep" if stills else shot.mode()
                r.say(f"shot {shot.name}: {mode}, {shot.n} frames")
                if mode == "substep" and not r.substep(shot, sdir):
                    r.say(f"  {shot.name}: the bridge did not answer: realtime instead")
                    mode = "realtime"
                if mode == "realtime":
                    r.realtime(shot, sdir)
                elif mode == "lockstep":
                    r.lockstep(shot, sdir, stills, route)
                mkv = os.path.join(sdir, "shot.mkv")
                if not stills and os.path.exists(mkv):
                    bad = jumps(mkv)
                    if bad:   # a frame that jumps away and back: cloth that saw a teleport (or a missed capture)
                        r.say(f"  WARNING {shot.name}: {len(bad)} frame(s) jump and snap back (frame, span, strength): "
                              f"{bad[:8]}")
        finally:
            r.restore()
            r.cmd(f"unbind {KEY_NEXT};demo_timescale 1", 0.3)
    if session is not None:
        body(session)
    else:
        with Session(os.path.join(dest, "session"), map=None, sourcetv=False, size=scene.window,
                     say=lambda m: (print(m), log.write(m + "\n"))) as s:
            body(s)
    log.close()


