# ---- chains --------------------------------------------------------------------------------------------------

def chain_text(scene, shot, frames=None, realtime=False):
    """The shot as an alias chain: `cin_next` runs the next frame. Lockstep frames step the demo first."""
    fr = frames or scene.frames(shot)
    name = chain_name(scene, shot)
    # a lead alias first: the first camera, captured by nobody. The first tap after a seek and the clean look did
    # not always land (2026-11-21: first frames of some shots kept the shot before's camera)
    out = [f"// generated by cinema/film.py from {os.path.basename(scene.path)}: {name}, {len(fr)} frames",
           f'alias cin_next "cf_lead"', f'alias cf_lead "{fr[0].spec_goto()};alias cin_next cf_{fr[0].k:05d}"']
    for i, f in enumerate(fr):
        nxt = f"cf_{fr[i + 1].k:05d}" if i + 1 < len(fr) else "cin_done"
        parts = []
        if realtime:
            if i == 0:
                parts.append("demo_resume")
        elif f.step > 0 and i > 0:
            parts.append(f"demo_step_tick {f.step}")
        parts.append(f.spec_goto())
        parts.append(f"alias cin_next {nxt}")
        out.append(f'alias cf_{f.k:05d} "{";".join(parts)}"')
    out.append('alias cin_done "echo cinema: last frame"')
    return "\n".join(out) + "\n"


def stills_of(frames, n):
    if n >= len(frames):
        return frames
    idx = sorted({round(i * (len(frames) - 1) / max(1, n - 1)) for i in range(n)})
    return [frames[i] for i in idx]


def write_chains(scenes, stills=0):
    os.makedirs(CHAIN_DIR, exist_ok=True)
    for f in os.listdir(CHAIN_DIR):   # the pak carries only the scenes being built
        if f.endswith(".cfg"):
            os.remove(os.path.join(CHAIN_DIR, f))
    written, bridge_paths = [], []
    for sc in scenes:
        for shot in sc.all_shots():
            if shot.card is not None:   # cards are drawn by the encoder: nothing to film
                continue
            fr = sc.frames(shot)
            rt = shot.mode() in ("realtime", "substep")
            if rt:   # also baked into the Panorama bridge: played a camera a rendered frame (F8) or stepped (F10)
                bridge_paths.append({"name": chain_name(sc, shot), "mode": "spec", "fps": sc.fps, "seconds": shot.length,
                                     "start": "demo_resume", "end": "demo_pause",
                                     "rates": [round(f.rate, 8) for f in fr],
                                     **({"clock": "frames", "warm": shot.warm_ticks() // 2, "warm_rate": 0.03125,
                                         "fps_max": PACED_FPS} if shot.mode() == "substep" else {}),
                                     "samples": [[round(f.pos[0], 2), round(f.pos[1], 2), round(f.pos[2], 2),
                                                  round(f.pitch, 3), round(f.yaw, 3)] for f in fr]})
            text = chain_text(sc, shot, fr, realtime=rt)
            path = os.path.join(CHAIN_DIR, chain_name(sc, shot) + ".cfg")
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            written.append(path)
            if stills:
                # stills: frames placed by seeking (each still is its own tick), so their chain has no steps
                st = stills_of(fr, stills)
                lines = [f'alias cin_next "cs_0"']
                for i, f_ in enumerate(st):
                    lines.append(f'alias cs_{i} "{f_.spec_goto()};alias cin_next cs_{i + 1}"')
                with open(os.path.join(CHAIN_DIR, chain_name(sc, shot) + "_stills.cfg"), "w", encoding="utf-8", newline="\n") as f:
                    f.write("\n".join(lines) + "\n")
    with open(BRIDGE_PATHS, "w", encoding="utf-8", newline="\n") as f:
        json.dump(bridge_paths, f, separators=(",", ":"))
    return written


def bridge_index():
    """The names of the paths baked into the built pak's bridge, in CINEMA_PATHS order (F11 arms 0, F9 the next)."""
    p = os.path.join(HERE, "addon", "panorama", "scripts", "cinema", "cinema_paths.js")
    if not os.path.exists(p):
        return []
    text = open(p, encoding="utf-8").read()
    body = text[text.index("=") + 1:].strip().rstrip(";")
    return [x["name"] for x in json.loads(body)]


def build(scenes, stills=0):
    write_chains(scenes, stills)
    r = subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", os.path.join(HERE, "cinema.ps1"), "build"],
                       capture_output=True, text=True)
    tail = (r.stdout.strip().splitlines() or [""])[-1]
    if r.returncode != 0:
        raise RuntimeError(f"cinema pak build failed: {r.stdout[-1500:]}{r.stderr[-500:]}")
    return tail


