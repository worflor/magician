SNIP_SLANT = 0.12
SNIP_GOLD = (190, 90, 230)   # G, B, R


def snip_expr():
    """Written out in full, with no st()/ld() registers: xfade evaluates the expression on several slice threads
    at once, and the registers are shared between them (it rendered as coloured noise)."""
    q = "(1-P)"
    yc = f"(H*0.52+(X-W/2)*{SNIP_SLANT})"
    sep = f"(H*0.62*pow(max(0,({q}-0.45)/0.55),2))"
    ys = f"if(lt(Y,{yc}),Y+{sep},Y-{sep})"
    a = f"if(eq(PLANE,0),a0(X,{ys}),if(eq(PLANE,1),a1(X,{ys}),a2(X,{ys})))"
    gold = f"if(eq(PLANE,0),{SNIP_GOLD[0]},if(eq(PLANE,1),{SNIP_GOLD[1]},{SNIP_GOLD[2]}))"
    keep = f"if(lt(Y,{yc}),lt({ys},{yc}),gt({ys},{yc}))"
    line = f"lt({q},0.5)*lt(X,W*min(1,{q}/0.45))*lt(abs(Y-{yc}),2.5)"
    return f"if({line},{gold},if({keep},{a},B))"


def snip_scissors(t0, d, w, h):
    """The scissors glyph riding the cut for its first 45 %, then flying off with the parting."""
    size = int(h * 0.13)
    t1 = t0 + d * 0.45
    x = f"((t-{t0:.4f})/{d * 0.45:.4f})*{w}-text_w*0.35"
    y = f"{h * 0.52:.1f}+(({x})+text_w*0.35-{w / 2:.1f})*{SNIP_SLANT}-text_h/2"
    return (f"drawtext=fontfile='{FONTS}seguisym.ttf':text='✂':fontsize={size}:fontcolor=0xe8c66a:"
            f"borderw=3:bordercolor=0x2a1a10:x='{x}':y='{y}':enable='between(t,{t0:.4f},{t1:.4f})'")


def layer_expr(keys, axis, span):
    """An overlay position as an ffmpeg expression of t: the keys' values (fractions of the output) times span,
    eased between keys (the ease of the key a move ends on), held before the first key and after the last."""
    def ease(e, u):
        return {"linear": u, "in": f"pow({u},3)", "out": f"(1-pow(1-{u},3))",
                "inout": f"({u})*({u})*(3-2*({u}))"}[e]
    v = [round(k[axis] * span, 3) for k in keys]
    expr = f"{v[-1]}"
    for n in range(len(keys) - 1, 0, -1):
        t0, t1 = keys[n - 1][0], keys[n][0]
        if t1 - t0 < 1e-6:
            seg = f"{v[n]}"
        else:
            u = f"((t-{t0:.6f})/{t1 - t0:.6f})"
            seg = f"{v[n - 1]}+({v[n] - v[n - 1]})*{ease(keys[n][3], u)}"
        expr = f"if(lt(t,{t1:.6f}),{seg},{expr})"
    return f"if(lt(t,{keys[0][0]:.6f}),{v[0]},{expr})"   # quoted in the graph: the commas are safe


def key_expr(keys, idx, scale, var):
    """A key value (index idx of the keys, times scale) as an ffmpeg expression of `var` (time in seconds), eased
    between keys like layer_expr; held before the first key and after the last."""
    def ease(e, u):
        return {"linear": u, "in": f"pow({u},3)", "out": f"(1-pow(1-{u},3))",
                "inout": f"({u})*({u})*(3-2*({u}))"}[e]
    v = [round(k[idx] * scale, 5) for k in keys]
    expr = f"{v[-1]}"
    for n in range(len(keys) - 1, 0, -1):
        t0, t1 = keys[n - 1][0], keys[n][0]
        if t1 - t0 < 1e-6 or v[n] == v[n - 1]:
            seg = f"{v[n]}"
        else:
            u = f"(({var}-{t0:.6f})/{t1 - t0:.6f})"
            seg = f"{v[n - 1]}+({round(v[n] - v[n - 1], 5)})*{ease(keys[n][3], u)}"
        expr = f"if(lt({var},{t1:.6f}),{seg},{expr})"
    return f"if(lt({var},{keys[0][0]:.6f}),{v[0]},{expr})"


CARD_IVORY, CARD_INK = "0xf2ede2", "0x3a2f2a"


def card_chain(L, lab, inp, ow, oh, fps, grade_frag, still, n_frames):
    """A collage card: the layer's picture mounted on a print (a polaroid: an ivory border and a deeper foot with its
    caption, a soft shadow) and placed by a per-frame perspective warp on a transparent frame the size of the output,
    so it can move, scale and turn on its keys (centre x, y in fractions of the output, a scale of `size`, degrees).
    Returns the chains (the card ends in [<lab>c], RGBA at the output size) for overlay from its first key."""
    pw, ph = max(2, round(L["size"][0] * ow)), max(2, round(L["size"][1] * oh))
    cx, cy, cw, ch = L["crop"]
    out = []
    # an image loops its one frame; a held layer shot repeats its last frame (the card moves on after it ends); both
    # bounded to the host's frames (an endless stream never lets the encode finish). Orders that work (ffmpeg 7.1):
    # loop, then trim before fps (fps buffers an endless stream forever); tpad only after fps (it needs the rate)
    if L["image"] is not None:
        lead = f"loop=loop=-1:size=1:start=0,settb=1/{fps},setpts=N,trim=end_frame={n_frames},fps={fps},"
    elif still:
        lead = f"settb=1/{fps},setpts=N,fps={fps},tpad=stop={n_frames}:stop_mode=clone,trim=end_frame={n_frames},"
    else:
        lead = f"settb=1/{fps},setpts=N,fps={fps},trim=end_frame={n_frames},"
    src = (f"[{inp}:v]{lead}settb=1/{fps},"
           f"format=rgb24,crop=iw*{cw:.6f}:ih*{ch:.6f}:iw*{cx:.6f}:ih*{cy:.6f},scale={pw}:{ph}:flags=lanczos[{lab}p]")
    out.append(src)
    out.append(grade_frag(f"{lab}p", f"{lab}g", f"{lab}q"))
    if L["card"] == "polaroid":
        m = max(4, round(pw * 0.055))
        foot = max(m * 3, round(ph * 0.26))
        cap = ""
        if L["caption"]:
            # cut 5: captions sized for a phone (cut 4's were 0.38 of the foot, 24 px at 1080p), and never wider than
            # the print (Palatino italic runs about 0.47 em a character)
            fs = max(10, min(round(foot * 0.46), int((pw + 2 * m) * 0.9 / (0.47 * max(1, len(L["caption"]))))))
            cap = (f",drawtext=fontfile='{FONTS}palai.ttf':text='{_dt(L['caption'])}':fontsize={fs}:"
                   f"fontcolor={CARD_INK}:x=(w-text_w)/2:y=h-{foot}+({foot}-text_h)/2-{round(m * 0.15)}")
        out.append(f"[{lab}g]format=rgba,drawbox=x=0:y=0:w=iw:h=ih:color=0x000000@0.18:t=1,"
                   f"pad=iw+{2 * m}:ih+{m + foot}:{m}:{m}:color={CARD_IVORY}{cap}[{lab}f]")
        bw, bh = pw + 2 * m, ph + m + foot
    else:
        b = L["border"]
        box = f",drawbox=x=0:y=0:w=iw:h=ih:color={L['border_color']}:t={b}" if b > 0 else ""
        out.append(f"[{lab}g]format=rgba{box}[{lab}f]")
        bw, bh = pw, ph
    # the shadow: the print in black at 45 %, blurred, under the print offset down and right; a clear margin round
    # both so the warp's edge pixels are transparent
    s = max(6, round(bw * 0.07))
    dx, dy = max(2, round(bw * 0.018)), max(3, round(bw * 0.03))
    out.append(f"[{lab}f]pad=iw+{2 * s}:ih+{2 * s}:{s}:{s}:color=0x00000000,split[{lab}a][{lab}b];"
               f"[{lab}b]colorchannelmixer=rr=0:gg=0:bb=0:aa=0.45,gblur=sigma={max(2, round(s * 0.35))}[{lab}s];"
               f"[{lab}s][{lab}a]overlay=x=-{dx}:y=-{dy}:format=auto,"
               f"pad=iw+8:ih+8:4:4:color=0x00000000[{lab}d]")   # clear edges: the warp repeats its edge pixels
    tw, th = bw + 2 * s + 8, bh + 2 * s + 8          # the padded print, in output pixels at scale 1
    T = f"(in/{fps})"
    X, Y = key_expr(L["keys"], 1, ow, T), key_expr(L["keys"], 2, oh, T)
    S, R = key_expr(L["keys"], 4, 1.0, T), key_expr(L["keys"], 5, math.pi / 180, T)
    corners = []
    for sx, sy in ((-1, -1), (1, -1), (-1, 1), (1, 1)):
        ux, uy = f"({sx * tw / 2:g}*({S}))", f"({sy * th / 2:g}*({S}))"
        corners.append((f"({X})+{ux}*cos({R})-{uy}*sin({R})", f"({Y})+{ux}*sin({R})+{uy}*cos({R})"))
    names = ["x0", "y0", "x1", "y1", "x2", "y2", "x3", "y3"]
    vals = [c for xy in corners for c in xy]
    persp = ":".join(f"{n}='{v}'" for n, v in zip(names, vals))
    out.append(f"[{lab}d]scale={ow}:{oh}:flags=bicubic,format=gbrap,"
               f"perspective={persp}:sense=destination:eval=frame:interpolation=cubic[{lab}c]")
    return out


def image_sources(scene):
    """The still images the timeline's layers read, in the order assemble() adds them as inputs (after the shots)."""
    out = []
    for shot in scene.shots:
        for L in shot.layers:
            if L.get("image") and L["image"] not in out:
                out.append(L["image"])
    return out


def fc(graph):
    """The filter graph as ffmpeg arguments: inline, or from a script file when it is too long for a Windows command
    line (32 767 characters; the collage's card warps run to hundreds of thousands)."""
    if len(graph) < 24000:
        return ["-filter_complex", graph]
    import tempfile
    fd, path = tempfile.mkstemp(suffix=".ffgraph")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(graph)
    return ["-filter_complex_script", path]


def assemble(scene, inputs, size, zoom=True, burn=None, grade=True):
    """The edit as one ffmpeg filter graph: each shot (its ffmpeg input arguments in `inputs`) zoomed or scaled to
    `size`, graded, the cuts, dissolves, fades, dips and snips between them. Returns (input args, graph, output
    label, length)."""
    import grade as gr
    fps = scene.fps
    ow, oh = size
    args, chains, labels, images = [], [], [], []
    for i, shot in enumerate(scene.shots):
        args += inputs[i]
        # xfade wants one constant rate and timebase. The pts are renumbered from the frame count first: the shot
        # files carry millisecond pts (31, 63, 94 ...), and after the head's trim and tpad the fps filter dropped a
        # frame of every shot (cut 2's render: each cut a frame earlier than the last, s23 14 frames off the music)
        f = [f"settb=1/{fps}", "setpts=N", f"fps={fps}", f"settb=1/{fps}", "format=rgb24"]
        if shot.head > 0 and shot.card is None:   # the first frames replaced by copies of frame `head`
            f[2:2] = [f"trim=start_frame={shot.head}", "setpts=N", f"tpad=start={shot.head}:start_mode=clone", "setpts=N"]
        z = shot.zoom
        if zoom and z != 1.0 and z != [1.0, 1.0]:
            n = max(1, shot.n - 1)
            if isinstance(z, (int, float)):
                zexpr = f"{float(z)}"
            elif isinstance(z, list) and len(z) == 2 and all(isinstance(v, (int, float)) for v in z):
                u = f"min(1,on/{n})"
                e = f"({u})*({u})*(3-2*({u}))" if shot.zoom_ease == "inout" else u
                zexpr = f"{z[0]}+({z[1]}-{z[0]})*{e}"
            else:
                raise RuntimeError(f"{shot.where}: encode supports zoom as a number or [from, to]")
            # a crop of the rendered frame scaled to the output: from a window larger than the output (scene.window)
            # the zoom keeps full detail up to window/output
            f.append(f"zoompan=z='{zexpr}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d=1:s={ow}x{oh}:fps={fps}")
        else:
            f.append(f"scale={ow}:{oh}:flags=lanczos")   # supersampled down when the window is larger
        for a, b, c, e, zz, px, py in (shot.punch if zoom else []):   # a crash zoom on a point, eased in and out
            t = f"(in/{fps})"
            def sm(lo, hi):
                u = f"clip(({t}-{lo:.4f})/{max(hi - lo, 1e-3):.4f},0,1)"
                return f"({u}*{u}*(3-2*{u}))"
            # a punch that starts at the cut is held from the shot's first frame (cut 5: s04's and s07's first frames
            # came out uncropped, a one-frame pop, because the ease in began at zoom 1 on frame 0)
            w = f"({'1' if a <= 0 else sm(a, b)}*(1-{sm(c, e)}))"
            f.append(f"zoompan=z='1+{zz - 1:g}*{w}':x='clip({px:g}*iw-iw/zoom/2,0,iw-iw/zoom)':"
                     f"y='clip({py:g}*ih-ih/zoom/2,0,ih-ih/zoom)':d=1:s={ow}x{oh}:fps={fps},setsar=1")
        chains.append(f"[{i}:v]{','.join(f)}[p{i}]")
        look = shot.grade if (grade and shot.card is None) else "none"
        chains.append(gr.fragment(look, f"p{i}", f"g{i}", f"q{i}"))
        cur = f"g{i}"
        for n, L in enumerate(shot.layers):   # panels over the host: cropped, scaled, graded, moved on keys
            if L["image"] is not None:          # a still from a file: its input after every shot's
                if L["image"] not in images:
                    images.append(L["image"])
                j = len(inputs) + images.index(L["image"])
            else:
                j = len(scene.shots) + scene.layer_shots.index(L["src"])
                if j >= len(inputs):
                    continue
            if L["transform"]:                  # a card: mounted, warped onto its keys, drawn from its first key
                lab = f"L{i}_{n}"
                look = L["grade"] if grade else "none"
                chains.extend(card_chain(L, lab, j, ow, oh, fps, lambda a, b, c, look=look: gr.fragment(look, a, b, c),
                                         L["image"] is not None or L["hold"], shot.n))
                t_on = L["keys"][0][0]
                chains.append(f"[{cur}][{lab}c]overlay=x=0:y=0:format=auto:eof_action=pass:"
                              f"enable='gte(t,{t_on:.4f})',format=rgb24[{lab}o]")
                cur = f"{lab}o"
                continue
            pw, ph = max(2, round(L["size"][0] * ow)), max(2, round(L["size"][1] * oh))
            cx, cy, cw, ch = L["crop"]
            lab = f"L{i}_{n}"
            hd = L["src"].head
            trim = f"trim=start_frame={hd},setpts=N,tpad=start={hd}:start_mode=clone,setpts=N," if hd > 0 else ""
            chains.append(f"[{j}:v]settb=1/{fps},setpts=N,{trim}fps={fps},settb=1/{fps},format=rgb24,"
                          f"crop=iw*{cw:.6f}:ih*{ch:.6f}:iw*{cx:.6f}:ih*{cy:.6f},scale={pw}:{ph}:flags=lanczos[{lab}p]")
            chains.append(gr.fragment(L["grade"] if grade else "none", f"{lab}p", f"{lab}g", f"{lab}q"))
            b = L["border"]
            box = f",drawbox=x=0:y=0:w=iw:h=ih:color={L['border_color']}:t={b}" if b > 0 else ""
            chains.append(f"[{lab}g]format=rgb24{box}[{lab}b]")
            chains.append(f"[{cur}][{lab}b]overlay=x='{layer_expr(L['keys'], 1, ow)}':y='{layer_expr(L['keys'], 2, oh)}':"
                          f"eval=frame:eof_action={'repeat' if L['hold'] else 'pass'},format=rgb24[{lab}o]")
            cur = f"{lab}o"
        if shot.flash and grade:   # a white hit, weighted to the frame's bright parts (a bloom), decaying
            k = "+".join(f"{st:g}*gte(T,{at:.4f})*exp(-(T-{at:.4f})/{max(dc, 0.01):.4f})" for at, st, dc in shot.flash)
            chains.append(f"[{cur}]format=gbrp,split[{cur}fa][{cur}fb];[{cur}fb]gblur=sigma=36[{cur}fc];"
                          f"[{cur}fa][{cur}fc]blend=all_expr='A+clip({k},0,1)*(255-A)*(0.35+0.65*B/255)',"
                          f"format=rgb24[{cur}F]")
            cur = f"{cur}F"
        if shot.shake and grade:   # the frame jolted: a margin cropped, the window moved on decaying sines
            m = max(a for _, a, _, _ in shot.shake) + 2
            def wave(phase, mul):
                return "+".join(f"{a:g}*gte(t,{at:.4f})*exp(-(t-{at:.4f})/{max(dc, 0.01):.4f})"
                                f"*sin(2*PI*{hz * mul:g}*(t-{at:.4f})+{phase})" for at, a, dc, hz in shot.shake)
            chains.append(f"[{cur}]scale={ow + 2 * m}:{oh + 2 * m}:flags=lanczos,"
                          f"crop={ow}:{oh}:x='clip({m}+{wave(0, 1)},0,{2 * m})':y='clip({m}+{wave(1.3, 1.37)},0,{2 * m})',"
                          f"setsar=1,format=rgb24[{cur}S]")
            cur = f"{cur}S"
        fades = []
        if shot.cut == "fade" or (shot.cut in ("dissolve", "dip", "snip") and i == 0):
            fades.append(f"fade=t=in:st=0:d={shot.cut_len}")
        if i + 1 < len(scene.shots) and scene.shots[i + 1].cut == "dip":
            nxt = scene.shots[i + 1]
            fades.append(f"fade=t=out:st={max(0, shot.length - nxt.cut_len)}:d={nxt.cut_len}")
        chains.append(f"[{cur}]{','.join(fades) or 'null'},format=rgb24[s{i}]")
        labels.append(f"s{i}")
    for extra in inputs[len(scene.shots):]:   # the layer sources' inputs, after the timeline's (indexed so)
        args += extra
    for im in images:                         # the stills of image layers, after them
        args += ["-i", im]
    acc, acc_len = labels[0], scene.shots[0].length
    for i in range(1, len(scene.shots)):
        shot = scene.shots[i]
        out = f"a{i}"
        if shot.cut in ("dissolve", "snip"):
            d = min(shot.cut_len, acc_len, shot.length)
            if shot.cut == "dissolve":
                chains.append(f"[{acc}][s{i}]xfade=transition=fade:duration={d}:offset={acc_len - d},settb=1/{fps}[{out}]")
            else:
                # the custom expression reads planes (a0, a1, a2): planar gbrp in, not packed rgb24
                chains.append(f"[{acc}]format=gbrp[{acc}p];[s{i}]format=gbrp[s{i}p];"
                              f"[{acc}p][s{i}p]xfade=transition=custom:expr='{snip_expr()}':duration={d}:"
                              f"offset={acc_len - d},settb=1/{fps},format=rgb24,{snip_scissors(acc_len - d, d, ow, oh)}[{out}]")
            acc_len += shot.length - d
        else:
            # timestamps renumbered from the frame count on both sides: after a snip (xfade plus the scissors'
            # overlays) every later concat lost a frame (cut 2's render: s21 landed 12 frames early on the music)
            chains.append(f"[{acc}]setpts=N/({fps}*TB)[{acc}n];[s{i}]setpts=N/({fps}*TB)[s{i}n];"
                          f"[{acc}n][s{i}n]concat=n=2:v=1:a=0,settb=1/{fps},setpts=N/({fps}*TB),fps={fps}[{out}]")
            acc_len += shot.length
        acc = out
    if burn:
        # subtitles= wants its path escaped for the filter parser: forward slashes, the drive colon escaped
        esc = burn.replace("\\", "/").replace(":", "\\:")
        chains.append(f"[{acc}]subtitles='{esc}':force_style='FontSize=14,Outline=1,MarginV=8'[burned]")
        acc = "burned"
    return args, ";".join(chains), acc, acc_len



# The mix's ceiling: limited at 4x oversampling to -2 dBFS, so the lossy copies (AAC in preview.mp4 and phone.mp4) stay
# under 0 dBTP. Cut 3's mix was limited at -0.5 dBFS sample peak and its AAC peaked at +2.3 dBFS (inter-sample overs).
MIX_CEILING = 0.794

def audio_mix(scene, length, first_input):
    """The film's sound: the [music] track and every [[sfx]] event, each at its film time and gain, summed (no
    normalisation: the gains are the mix) and limited. Returns (input args, graph, label) or None when silent.
    The game's own sound is not captured with the frames, so its effects and voice lines come in as [[sfx]] from
    decoded files (dev only: Valve's audio never ships)."""
    args, chains, labels, k = [], [], [], first_input
    m = scene.music
    if m is not None and m.file:
        if not os.path.exists(m.file):
            raise RuntimeError(f"[music] file {m.file} does not exist")
        args += ["-i", m.file]
        chains.append(f"[{k}:a]aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo,volume={m.gain}dB[mu]")
        labels.append("[mu]")
        k += 1
    for j, e in enumerate(scene.sfx):
        if not os.path.exists(e["file"]):
            raise RuntimeError(f"[[sfx]] {e['name']}: {e['file']} does not exist")
        args += ["-i", e["file"]]
        ms = max(0, int(round(e["at"] * 1000)))
        chains.append(f"[{k}:a]aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo,volume={e['gain']}dB,"
                      f"adelay={ms}:all=1[x{j}]")
        labels.append(f"[x{j}]")
        k += 1
    if not labels:
        return None
    chains.append("".join(labels) + f"amix=inputs={len(labels)}:normalize=0:duration=longest,"
                  f"apad,atrim=0:{length:.4f},aresample=192000,alimiter=limit={MIX_CEILING}:attack=2:release=60:"
                  f"level=disabled,aresample=48000[aout]")
    return args, ";".join(chains), "aout"


LOSSY_CEILING = 0.708   # -3 dBFS: the AAC copies limited again before the encoder (cut 5: the phone copy's AAC at 160k
                        # overshot the -2 dBFS mix by 3.5 dB, a true peak of +1.5 dBFS; limited here, -1.6)


def lossy(dest, master, length, sound):
    """preview.mp4 (x264 CRF 16, AAC 256k) and phone.mp4 (two-pass x264 to PHONE_MB, AAC 160k) from the master. Each
    AAC is fed a copy limited to LOSSY_CEILING at 4x oversampling, so the lossy encode has room for its overshoot."""
    af = ["-af", f"aresample=192000,alimiter=limit={LOSSY_CEILING}:attack=1:release=50:level=disabled,aresample=48000"]
    preview = os.path.join(dest, "preview.mp4")
    subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", master, "-c:v", "libx264", "-preset", "slow",
                    "-crf", "16", "-pix_fmt", "yuv420p"] + (af + ["-c:a", "aac", "-b:a", "256k"] if sound else [])
                   + ["-movflags", "+faststart", preview], check=True)
    outs = [preview]
    if PHONE_MB > 0:   # a copy that fits a message: two-pass x264 to a size, AAC 160k
        phone = os.path.join(dest, "phone.mp4")
        kbps = int((PHONE_MB * 8000 * 0.97) / max(1.0, length) - (160 if sound else 0))
        log = os.path.join(dest, "phone2pass")
        v = ["-c:v", "libx264", "-preset", "slow", "-b:v", f"{kbps}k", "-pix_fmt", "yuv420p", "-passlogfile", log]
        subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", master] + v + ["-pass", "1", "-an", "-f", "mp4",
                        os.devnull], check=True)
        subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", master] + v + ["-pass", "2"]
                       + (af + ["-c:a", "aac", "-b:a", "160k"] if sound else []) + ["-movflags", "+faststart", phone], check=True)
        for f in os.listdir(dest):
            if f.startswith("phone2pass"):
                os.remove(os.path.join(dest, f))
        outs.append(phone)
    return outs



def encode(scene, keep_frames=True):
    dest = out_dir(scene)
    inputs = [shot_input(scene, shot, dest) for shot in scene.all_shots()]
    args, graph, acc, length = assemble(scene, inputs, scene.output)
    sound = audio_mix(scene, length, len(scene.all_shots()) + len(image_sources(scene)))
    amap = []
    if sound:
        args += sound[0]
        graph += ";" + sound[1]
        amap = ["-map", f"[{sound[2]}]", "-c:a", "flac"]
    master, preview = os.path.join(dest, "master.mkv"), os.path.join(dest, "preview.mp4")
    base = ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error"] + args + fc(graph) + ["-map", f"[{acc}]",
                                                                           "-r", str(scene.fps)]
    subprocess.run(base + ["-c:v", "ffv1", "-level", "3", "-pix_fmt", "bgr0"] + amap + [master], check=True)
    outs = [master] + lossy(dest, master, length, bool(sound))
    for p in outs:
        print(f"ENCODE {p} {os.path.getsize(p) / 1e6:.1f} MB")
    print(f"  {length:.2f} s at {scene.fps} fps{', with sound' if sound else ''}; edit files: "
          + ", ".join(os.path.basename(x) for x in edit_files(scene, dest)))
    if not keep_frames:
        shutil.rmtree(os.path.join(dest, "shots"), ignore_errors=True)
        print("  frames removed (the master is lossless)")
    return master, preview


def tc(seconds, fps):
    f = int(round(seconds * fps))
    return f"{f // (3600 * fps):02d}:{f // (60 * fps) % 60:02d}:{f // fps % 60:02d}:{f % fps:02d}"


def srt_time(seconds):
    ms = int(round(seconds * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def edit_files(scene, dest):
    """What the editor gets beside the master: shots.csv (every shot: film in/out, demo ticks, speed, camera),
    edit.edl (CMX 3600, one event a shot cut from the master, dissolves marked), slate.srt (the shot names over
    their shots) and cues.srt (the scene's music and sound cues at their film time, for the edit's audio)."""
    os.makedirs(dest, exist_ok=True)
    fps = scene.fps
    rows = []
    for s, a, b in scene.timeline():
        whole, _ = s.ticks()
        rows.append((s, a, b, whole[0], whole[-1]))
    with open(os.path.join(dest, "shots.csv"), "w", encoding="utf-8", newline="\n") as f:
        f.write("shot,name,in_s,out_s,length_s,tick_from,tick_to,speed,camera,cut,cues\n")
        for s, a, b, t0, t1 in rows:
            cues = " | ".join(c[1] for c in s.cues).replace(",", ";")
            f.write(f"{s.index + 1},{s.name},{a:.3f},{b:.3f},{s.length:.3f},{t0},{t1},\"{s.speed}\",{s.cam['type']},"
                    f"{s.cut}{' ' + format(s.cut_len, 'g') if s.cut != 'cut' else ''},{cues}\n")
    with open(os.path.join(dest, "edit.edl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"TITLE: {scene.name}\nFCM: NON-DROP FRAME\n\n")
        for n, (s, a, b, t0, t1) in enumerate(rows, 1):
            kind = f"D    {int(round(s.cut_len * fps)):03d}" if s.cut in ("dissolve", "snip") and n > 1 else "C        "
            f.write(f"{n:03d}  MASTER   V     {kind} {tc(a, fps)} {tc(b, fps)} {tc(a, fps)} {tc(b, fps)}\n")
            f.write(f"* FROM CLIP NAME: {s.name}\n* COMMENT: demo ticks {t0}-{t1}, speed {s.speed}, {s.cam['type']} camera"
                    f"{', cut ' + s.cut if s.cut != 'cut' else ''}\n\n")
    with open(os.path.join(dest, "slate.srt"), "w", encoding="utf-8", newline="\n") as f:
        for n, (s, a, b, t0, t1) in enumerate(rows, 1):
            f.write(f"{n}\n{srt_time(a)} --> {srt_time(b)}\n{n}. {s.name}  ticks {t0}-{t1}  x{s.speed}\n\n")
    with open(os.path.join(dest, "cues.srt"), "w", encoding="utf-8", newline="\n") as f:
        for n, (at, text) in enumerate(scene.cues(), 1):
            f.write(f"{n}\n{srt_time(at)} --> {srt_time(at + 2.0)}\n{text}\n\n")
    return [os.path.join(dest, x) for x in ("shots.csv", "edit.edl", "slate.srt", "cues.srt")]


def animatic(scene, size=(640, 360)):
    """The scene's timing and framing without the game: animatic.py draws every frame (cards as the encoder draws
    them), the edit is assembled the same way as the film's (grades, cuts, snips), the shot slate and the cues
    burned in, and the [music] track and [[sfx]] events mixed under it."""
    import animatic as anim
    dest = out_dir(scene)
    os.makedirs(dest, exist_ok=True)
    files = edit_files(scene, dest)
    out = os.path.join(dest, "animatic.mp4")
    parts, colours = anim.render(scene, out, size)
    # the slate and the cues together, burned in
    both = os.path.join(dest, "animatic.srt")
    with open(both, "w", encoding="utf-8", newline="\n") as f:
        f.write(open(files[2], encoding="utf-8").read())
        n = sum(1 for line in open(files[2], encoding="utf-8") if "-->" in line)
        for k, block in enumerate(open(files[3], encoding="utf-8").read().strip().split("\n\n"), 1):
            if "-->" in block:
                lines = block.split("\n")
                f.write(f"{n + k}\n{lines[1]}\ncue: {' '.join(lines[2:])}\n\n")
    inputs = [card_input(scene, sh, size) if sh.card is not None else ["-i", p] for sh, p in zip(scene.all_shots(), parts)]
    args, graph, acc, length = assemble(scene, inputs, size, zoom=False, burn=both)
    sound = audio_mix(scene, length, len(scene.all_shots()) + len(image_sources(scene)))
    amap = []
    if sound:
        args += sound[0]
        graph += ";" + sound[1]
        amap = ["-map", f"[{sound[2]}]", "-c:a", "aac", "-b:a", "192k"]
    try:
        subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error"] + args + fc(graph) + ["-map",
                        f"[{acc}]", "-r", str(scene.fps), "-c:v", "libx264", "-preset", "veryfast", "-crf", "23",
                        "-pix_fmt", "yuv420p"] + amap + ["-movflags", "+faststart", out], check=True)
    finally:
        for p in parts:
            if p and os.path.exists(p):
                os.remove(p)
    legend = ", ".join(f"{n} rgb{c}" for n, c in colours.items())
    print(f"ANIMATIC {out} {os.path.getsize(out) / 1e6:.1f} MB, {length:.2f} s{', with sound' if sound else ''} ({legend})")
    return out


def photomatic(scene, size=(1280, 720)):
    """The animatic from a stills pass (`render --stills N`): each shot's stills, each held from its own frame to
    the next one's, zoomed, graded, cut, snipped and scored exactly as the film will be, with the shot slate burned
    in. Real light, walls and framing at the film's timing, for approval before the full render. A shot
    with no stills yet shows the offline animatic's frame for it (a grey card naming it)."""
    dest = out_dir(scene)
    os.makedirs(dest, exist_ok=True)
    files = edit_files(scene, dest)
    tmp = os.path.join(dest, "photomatic_parts")
    os.makedirs(tmp, exist_ok=True)
    inputs = []
    for shot in scene.all_shots():
        if shot.card is not None:
            inputs.append(card_input(scene, shot, size))
            continue
        sdir = os.path.join(dest, "shots", shot.name + "_stills")
        pngs = sorted(f for f in os.listdir(sdir) if f.startswith("f") and f.endswith(".png")) if os.path.isdir(sdir) else []
        n = max(1, shot.n)
        if not pngs:
            txt = shot.name.replace(":", "")
            inputs.append(["-f", "lavfi", "-i", f"color=c=0x303030:s={size[0]}x{size[1]}:r={scene.fps}:d={n / scene.fps:.4f},"
                           f"drawtext=fontfile='{FONTS}segoeui.ttf':text='{txt} (no stills)':fontcolor=white:fontsize=36:"
                           "x=(w-text_w)/2:y=(h-text_h)/2"])
            continue
        # every frame of the shot as a file (a hard link to the still it holds), read at the scene's rate: the
        # concat demuxer's durations reached zoompan as a handful of frames and the shots ran short
        ks = [int(f[1:6]) for f in pngs]
        sd = os.path.join(tmp, shot.name)
        os.makedirs(sd, exist_ok=True)
        for k in range(n):
            j = max(i for i, kk in enumerate(ks) if kk <= k) if k >= ks[0] else 0
            dst = os.path.join(sd, f"f{k:05d}.png")
            try:
                os.link(os.path.join(sdir, pngs[j]), dst)
            except OSError:
                shutil.copyfile(os.path.join(sdir, pngs[j]), dst)
        inputs.append(["-framerate", str(scene.fps), "-i", os.path.join(sd, "f%05d.png")])
    out = os.path.join(dest, "photomatic.mp4")
    args, graph, acc, length = assemble(scene, inputs, size, burn=files[2])
    sound = audio_mix(scene, length, len(scene.all_shots()) + len(image_sources(scene)))
    amap = []
    if sound:
        args += sound[0]
        graph += ";" + sound[1]
        amap = ["-map", f"[{sound[2]}]", "-c:a", "aac", "-b:a", "192k"]
    try:
        subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error"] + args + fc(graph) + ["-map",
                        f"[{acc}]", "-t", f"{length:.4f}", "-r", str(scene.fps), "-c:v", "libx264", "-preset", "veryfast",
                        "-crf", "20", "-pix_fmt", "yuv420p"] + amap + ["-movflags", "+faststart", out], check=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print(f"PHOTOMATIC {out} {os.path.getsize(out) / 1e6:.1f} MB, {length:.2f} s{', with sound' if sound else ''}")
    return out


