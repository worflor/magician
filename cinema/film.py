def plan_png(scene, path, size=1200, plan_take=None):
    """Top-down: every actor's path over the scene's ticks (grey; the shot's actors white), every shot's camera path
    in its own colour with a view tick every few frames, start (filled square) and end (ring) of each."""
    from capture import write_png
    cols = [(255, 99, 71), (65, 180, 255), (120, 220, 90), (250, 200, 40), (210, 110, 255), (60, 220, 200), (255, 140, 200)]
    pts, segs = [], []
    # one take a plan: the main take's shots, or the first take used (a scene across takes: plan per take with --take)
    key = plan_take if plan_take else scene.shots[0].take_key
    shots_here = [s for s in scene.shots if s.take_key == key]
    lo = min(s.ticks()[0][0] for s in shots_here)
    hi = max(s.ticks()[0][-1] for s in shots_here)
    used = {(a, s.index) for s in shots_here for a in scn.Camera.actors_of(s.cam)}
    mine_names = {scene.actor(u, scene.shots[i]).name for u, i in used}
    tracks = []
    for name in scene.tracks_for(key).names():
        tr = scene.tracks_for(key).actors[name]
        line = [tr.at(t)[:2] for t in range(lo, hi + 1, 4)]
        mine = tr.name in mine_names
        tracks.append((name, line, mine))
        if mine:   # the frame fits the shots and their actors; other actors are drawn where they fall
            pts += line
    shots = []
    for i, s in enumerate(scene.shots):
        if s.take_key != key:
            continue
        fr = scene.frames(s)
        shots.append((cols[i % len(cols)], fr))
        pts += [f.pos[:2] for f in fr]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    span = max(max(xs) - min(xs), max(ys) - min(ys), 400) * 1.15
    cx, cy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    W = H = size
    img = bytearray(b"\x18\x18\x1c\x00" * W * H)

    def px(p):
        return int((p[0] - cx) / span * W + W / 2), int(H / 2 - (p[1] - cy) / span * H)

    def dot(x, y, c, r=1):
        for yy in range(y - r, y + r + 1):
            for xx in range(x - r, x + r + 1):
                if 0 <= xx < W and 0 <= yy < H:
                    o = (yy * W + xx) * 4
                    img[o:o + 3] = bytes((c[2], c[1], c[0]))

    def line(a, b, c, r=0):
        (x0, y0), (x1, y1) = px(a), px(b)
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for k in range(n + 1):
            dot(round(x0 + (x1 - x0) * k / n), round(y0 + (y1 - y0) * k / n), c, r)

    # grid every 250 units
    step = 250
    for gx in range(int((cx - span / 2) // step) * step, int(cx + span / 2) + step, step):
        line([gx, cy - span], [gx, cy + span], (34, 34, 40))
    for gy in range(int((cy - span / 2) // step) * step, int(cy + span / 2) + step, step):
        line([cx - span, gy], [cx + span, gy], (34, 34, 40))
    for name, ln, used_here in tracks:
        c = (235, 235, 235) if used_here else (90, 90, 96)
        for a, b in zip(ln, ln[1:]):
            line(a, b, c, 1 if used_here else 0)
    for c, fr in shots:
        for a, b in zip(fr, fr[1:]):
            line(a.pos, b.pos, c, 1)
        every = max(1, len(fr) // 12)
        for f in fr[::every] + [fr[-1]]:
            yw = math.radians(f.yaw)
            line(f.pos, [f.pos[0] + 90 * math.cos(yw), f.pos[1] + 90 * math.sin(yw)], c)
        x, y = px(fr[0].pos)
        dot(x, y, c, 5)
        x, y = px(fr[-1].pos)
        for a in range(0, 360, 10):
            dot(round(x + 7 * math.cos(math.radians(a))), round(y + 7 * math.sin(math.radians(a))), c, 1)
        # the actors where the shot starts (white square) and ends (white ring)
        for name in scn.Camera.actors_of(fr[0].shot.cam):
            tr = scene.actor(name, fr[0].shot)
            x, y = px(tr.at(fr[0].tick))
            dot(x, y, (255, 255, 255), 3)
            x, y = px(tr.at(fr[-1].tick))
            for a in range(0, 360, 15):
                dot(round(x + 5 * math.cos(math.radians(a))), round(y + 5 * math.sin(math.radians(a))), (255, 255, 255))
    write_png(path, W, H, bytes(img))
    legend = [f"plan {path}: take {key}, {span:.0f} units across, grid 250 units, north up"]
    for i, (c, fr) in enumerate(shots):
        legend.append(f"  rgb{c}: {fr[0].shot.name} (filled square: first frame, ring: last; white: its actors)")
    return "\n".join(legend)


# ---- rendering ----------------------------------------------------------------------------------------------

SHORT_SEEK = 320   # ticks (5 s): a forward move this short is stepped, never sought (see plan_seek)


def plan_seek(at_tick, target):
    """How to get the paused demo from `at_tick` (None: unknown) to `target`: ("stay", 0), ("step", n) or
    ("seek", target).

    A short forward `demo_gototick` does not skip: the demo plays on to its tick (no "Demo Skipping" line) and can
    be left running past it. The trailer's freeze (s20, tick 9822, warm-up from 9726) came straight after the latch
    (s19, last frame 9719) in the same take in cuts 2, 3 and 4: a 7-tick forward seek. Each first pass filmed the
    frozen orbit round an empty sky (the demo had played on, Lash had already slammed and landed), and the still
    check passed because the camera left on screen looked at a building. Rendered alone (a long seek from the take's
    start) it was right every time. So a forward move of up to SHORT_SEEK ticks from a known paused tick is a
    `demo_step_tick`, which is exact."""
    if at_tick is None or target < at_tick or target - at_tick > SHORT_SEEK:
        return ("seek", target)
    if target == at_tick:
        return ("stay", 0)
    return ("step", target - at_tick)


class Renderer:
    def __init__(self, session, scene, log, route_rt="auto"):
        self.s, self.sc, self.log = session, scene, log
        self.clean = False
        self.at_tick = None   # the tick the demo is known to be paused on (None after a playdemo or a played shot)
        self.route_rt = route_rt   # realtime shots: auto (the bridge where it is baked and answers), or taps

    def say(self, msg):
        line = f"{time.strftime('%H:%M:%S')} {msg}"
        print(line)
        self.log.write(line + "\n")
        self.log.flush()

    def cmd(self, line, pause=0.3):
        self.s.cmd(line, pause)

    def seek(self, tick, camera=None):
        """Pause, seek and wait for the skip to finish (a seek still skipping when the next command lands restarts
        the demo: ingame README). A short forward move from a known paused tick is stepped instead (plan_seek).
        `camera` (a spec_goto line, the shot's first) is set first, so the still check watches the shot's subject
        and not whatever the last camera left on screen."""
        if camera:
            self.cmd(camera, 0.2)
        how, n = plan_seek(self.at_tick, tick)
        if how != "seek":
            self.say(f"  tick {tick}: {'already there' if how == 'stay' else f'stepped {n} ticks from {self.at_tick}'}"
                     " (a short forward seek plays on instead of skipping)")
            if n:
                self.cmd(f"demo_step_tick {n}", 0.0)
                time.sleep(n / scn.TICK_RATE + 0.5)
            self.at_tick = tick
            self.wait_still(tick)
            return
        # After demo_step_tick the demo sits in a step pause that stalls a forward skip of more than one batch
        # (100 messages): the skip starts and never finishes (2026-11-21, s4). A resume and a pause on one line
        # (the same frame: nothing plays) clears it.
        self.cmd("demo_resume;demo_pause", 0.3)
        off = self.s.log_offset()
        self.cmd(f"demo_gototick {tick}", 0.2)
        # a seek to the tick the demo is already on prints nothing at all: no skip started within 3 s is that case
        if self.s.wait_log("Demo Skipping", 3, offset=off) and not self.s.wait_log("Skipping finished", 30, offset=off):
            self.say(f"WARNING: no 'Skipping finished' for tick {tick} within 30 s")
        time.sleep(1.0)
        self.wait_still(tick)
        self.at_tick = tick

    def wait_still(self, tick, timeout=25.0):
        """Wait until the picture holds still (the demo really paused where the seek put it). A forward seek can
        report nothing and keep playing up to its tick for seconds: maid_and_magician's frozen dive (2026-11-21)
        filmed the demo catching up from before the cast to the landing. Two small grabs 0.4 s apart, until two
        gaps in a row change less than 0.6 of 255 on average."""
        from capture import find_window, client_rect, grab
        hwnd = find_window()
        x, y, w, h = client_rect(hwnd)

        def small():
            px = grab(x, y, w, h, hwnd)
            step = max(1, w // 96) * 4
            return [px[o] + px[o + 1] + px[o + 2] for r in range(h // 12, h, h // 12)
                    for o in range(r * w * 4, (r + 1) * w * 4, step)]

        t0, prev, calm = time.time(), small(), 0
        while time.time() - t0 < timeout:
            time.sleep(0.4)
            cur = small()
            d = sum(abs(a - b) for a, b in zip(cur, prev)) / (3 * len(cur))
            prev = cur
            calm = calm + 1 if d < 0.6 else 0
            if calm >= 2:
                if time.time() - t0 > 1.5:
                    self.say(f"  the demo settled at tick {tick} after {time.time() - t0:.1f} s")
                return True
        self.say(f"  WARNING: the picture never held still after the seek to tick {tick} ({timeout:.0f} s)")
        return False

    def look(self):
        if self.clean or self.sc.look != "clean":
            return
        # cin_clean_full hides every Panorama panel, the console with it: console.py drives it blind from here on
        world = ";r_drawworld 0;r_drawskybox 0" if self.sc.world == "void" else ""
        self.cmd("exec cinema;cin_clean" + world, 0.4)
        self.cmd("cin_clean_full", 0.5)
        self.clean = True

    def restore(self):
        if self.clean:
            self.cmd("cin_hud", 0.5)
            self.clean = False

    def lockstep(self, shot, dest, stills=0, route="keys"):
        """route keys: one tap of the bound key a frame (the chain baked into the pak); route console: each frame
        typed (about 1.7 s a frame, but no pak rebuild: framing passes and quick iterations in one session)."""
        from capture import find_window, client_rect, grab, write_png
        import console
        fr = self.sc.frames(shot)
        name = chain_name(self.sc, shot) + ("_stills" if stills else "")
        todo = stills_of(fr, stills) if stills else fr
        os.makedirs(dest, exist_ok=True)
        hwnd = find_window()
        x, y, w, h = client_rect(hwnd)
        writers, t0, dark = [], time.perf_counter(), []
        # a full shot goes straight into a lossless FFV1 file (raw frames piped to ffmpeg: no PNG pile on the disk,
        # a 4K frame would be 12 MB); stills stay PNGs to look at
        sink = None if stills else FrameSink(os.path.join(dest, "shot.mkv"), w, h, self.sc.fps)
        for i, f in enumerate(todo):
            if i == 0 or stills:
                # stills are each their own tick: seek to every one (a seek costs a second or two). Stills are warmed
                # too (cut 2 of the trailer): a seek drops every effect an event spawned before it, so a cold still
                # of a Death Slam showed no cloche, no ribbons, nothing but the hero
                warm = shot.warm_ticks()
                self.seek(f.tick - warm, camera=f.spec_goto())
                if warm:   # play up to the first frame so cloth arrives simulated, not from the seek's teleport
                    self.cmd(f"demo_step_tick {warm}", 0.0)
                    time.sleep(warm / scn.TICK_RATE + 0.5)
                    self.wait_still(f.tick)
                self.at_tick = f.tick
                if i == 0:
                    for line in self.sc.pre + shot.pre:
                        self.cmd(line, 0.4)
                    if route == "keys":
                        self.cmd(f"exec cinema/{name};bind {KEY_NEXT} cin_next", 0.5)
                    self.look()
                console.ensure_focus()
            if route == "keys":
                if i == 0:   # the lead alias: the first camera once, not captured
                    console.tap(KEY_NEXT, 0.01)
                    time.sleep(0.5)
                console.tap(KEY_NEXT, 0.01)
            else:
                self.cmd((f"demo_step_tick {f.step};" if f.step > 0 and i > 0 and not stills else "") + f.spec_goto(), 0.0)
            wait = self.sc.settle + (f.step / scn.TICK_RATE if not stills else 0) + (0.6 if i == 0 else 0)
            time.sleep(wait)
            if i == 0 or stills:
                # the first camera after a seek can be overridden as the seek lands (2026-11-21: first stills of
                # several shots showed the camera somewhere else): set it once more before the grab
                self.cmd(f.spec_goto(), 0.0)
                time.sleep(0.4)
            px = grab(x, y, w, h, hwnd)
            if _flat(px, w, h):
                dark.append(f.k)
            if sink is not None:
                sink.write(px)
            else:
                th = threading.Thread(target=write_png, args=(os.path.join(dest, f"f{f.k:05d}.png"), w, h, px))
                th.start()
                writers.append(th)
                if len(writers) > 8:
                    writers.pop(0).join()
            if i % 50 == 0 or i == len(todo) - 1:
                self.say(f"  {shot.name} frame {f.k} ({i + 1}/{len(todo)}) tick {f.tick}, "
                         f"{(time.perf_counter() - t0) / (i + 1):.2f} s/frame")
        for th in writers:
            th.join()
        if sink is not None:
            sink.close()
        self.at_tick = todo[-1].tick   # stepped frame by frame (or sought still by still) and left paused there
        if route == "keys":
            self.cmd(f"unbind {KEY_NEXT}", 0.3)
        el = time.perf_counter() - t0
        self.say(f"  {shot.name}: {len(todo)} frames {w}x{h} in {el:.0f} s ({el / len(todo):.2f} s/frame)")
        if dark:
            self.say(f"  WARNING {shot.name}: {len(dark)} frame(s) nearly one colour (camera inside geometry?): "
                     f"{dark[:12]}{' ...' if len(dark) > 12 else ''}")
        return w, h

    def bridge_arm(self, name):
        """Arm a baked path in the shot's own look (a bridge that stops under r_drawpanorama 0 is found here, not
        after a silent take): with Panorama hidden and no answer, Panorama is shown (the HUD stays hidden by
        cin_clean) and the arm tried again. True when armed."""
        index = bridge_index()
        if self.route_rt == "taps" or name not in index:
            return False
        self.look()
        ok = self.arm(index.index(name), name)
        if not ok and self.clean and self.sc.look == "clean":
            self.cmd("r_drawpanorama 1", 0.6)
            ok = self.arm(index.index(name), name)
            if ok:
                self.say("  the bridge answers only with Panorama drawn: this shot is filmed with cin_clean "
                         "(HUD hidden, Panorama on)")
            else:
                self.cmd("cin_clean_full", 0.5)
        return ok

    def substep(self, shot, dest):
        """Slow motion below a tick a frame, frame by frame, paced: the game is slowed to a few rendered frames a
        second (fps_max), the bridge plays the shot one sample a rendered frame with host_framerate = the frame's
        rate (the demo moves exactly that much demo time a rendered frame, measured 2026-11-21), and every rendered
        frame is captured once, timed from the bridge's "frame k" lines in console.log: the picture of sample k is on
        screen from the frame after the one that logged k (PACED_LAG) until the next. False when the bridge does not
        answer (the caller falls back to realtime)."""
        from capture import find_window, client_rect, grab
        import console
        fr = self.sc.frames(shot)
        name = chain_name(self.sc, shot)
        self.seek(fr[0].tick - shot.warm_ticks())   # the bridge plays the warm-up from here to frame 0
