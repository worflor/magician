def main(a):
    if len(a) < 2 or a[0] not in ("check", "plan", "animatic", "photomatic", "build", "render", "encode", "lossy", "make"):
        sys.exit(__doc__)

    def opt(name, default=None):
        return a[a.index(name) + 1] if name in a else default

    paths = [p for p in a[1:] if p.endswith((".toml", ".json")) and not p.startswith("--")]
    try:
        scenes = [scn.load(p) for p in paths]
        for sc in scenes:
            print(sc.summary())
            for w in sc.check():
                print("warning:", w)
    except (scn.SceneError, scn.track.TrackError) as e:
        sys.exit(f"scene error: {e}")
    if a[0] == "check":
        return
    if a[0] == "plan":
        for sc in scenes:
            png = opt("--png") or os.path.join(out_dir(sc), "plan.png")
            os.makedirs(os.path.dirname(png), exist_ok=True)
            print(plan_png(sc, png))
        return
    if a[0] == "animatic":
        for sc in scenes:
            animatic(sc, tuple(int(v) for v in opt("--size", "640x360").split("x")))
        return
    if a[0] == "photomatic":
        for sc in scenes:
            photomatic(sc, tuple(int(v) for v in opt("--size", "1280x720").split("x")))
        return
    if a[0] == "lossy":   # preview.mp4 and phone.mp4 again from the master (the shot frames are gone after encode)
        for sc in scenes:
            dest = out_dir(sc)
            master = os.path.join(dest, "master.mkv")
            length = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                                           master], capture_output=True, text=True, check=True).stdout.strip())
            for p in lossy(dest, master, length, bool(sc.sfx) or sc.music is not None):
                print(f"ENCODE {p} {os.path.getsize(p) / 1e6:.1f} MB")
        return
    stills = int(opt("--stills", 0))
    only = set(opt("--shots").split(",")) if "--shots" in a else None
    if a[0] in ("build", "make"):
        print(build(scenes, stills))
    if a[0] in ("render", "make"):
        route = opt("--route", "console" if stills else "keys")
        if len(scenes) == 1:
            render(scenes[0], only, stills, route=route)
        else:   # one game session for every scene (a launch and a hand-back each cost minutes)
            from session import Session
            with Session(os.path.join(WORK, "films", "session"), map=None, sourcetv=False, size=scenes[0].window) as s:
                for sc in scenes:
                    render(sc, only, stills, session=s, route=route)
    if a[0] in ("encode", "make") and not stills:
        for sc in scenes:
            encode(sc, keep_frames="--keep-frames" in a)   # D: is tight; the master is lossless


if __name__ == "__main__":
    main(sys.argv[1:])
