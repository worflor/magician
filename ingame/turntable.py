"""Write a console.py scenario that turns a mimic bot in place in front of a dollied camera.

    python -I turntable.py --me 1476 -1396 20 --bot 1494 -1196 --dolly 110 --fov 45 --steps 8 --tag idle > tt.txt
    python -I console.py --out <run dir> --script tt.txt

How it works (all retail cvars, cheats on):
  - bot_mimic 1 makes every bot copy the local player's buttons and view angles; bot_mimic_yaw_offset turns
    the bot relative to us. Standing still and stepping the offset is a turntable. Pressing an ability key
    makes the bot cast it too, so ability frames can be shot from the front (see --cast).
  - citadel_camera_overrides_enabled + citadel_camera_override_x_offset dolly the third-person camera forward
    along the view, past our own hero, so our model sits behind the lens and only the bot is framed.
Captures are <tag>_<deg>.png, deg = the bot's turn away from facing the camera (0 = front, 90 = its left side).
"""
import math
import sys


def main(a):
    def opt(name, default, n=1, cast=float):
        if name not in a:
            return default
        i = a.index(name)
        v = [cast(x) for x in a[i + 1:i + 1 + n]]
        return v if n > 1 else v[0]

    mx, my, mz = opt("--me", [0, 0, 20], 3)
    bx, by = opt("--bot", [0, 100], 2)
    yaw = math.degrees(math.atan2(by - my, bx - mx))
    steps = int(opt("--steps", 8))
    tag = opt("--tag", "tt", cast=str)
    settle = opt("--settle", 1.0)
    print("# generated by turntable.py")
    print("sv_cheats 1")
    print("citadel_hud_visible 0")
    print("bot_mimic 1")
    print("citadel_camera_overrides_enabled 1")
    print(f"citadel_camera_override_x_offset {opt('--dolly', 110)}")
    print(f"citadel_camera_override_y_offset {opt('--side', 0)}")
    print(f"citadel_camera_override_z_offset {opt('--up', 0)}")
    fov = opt("--fov", 0)
    if fov:
        print(f"citadel_camera_override_fov {fov}")
    print(f"setpos {mx:.1f} {my:.1f} {mz:.1f};setang {opt('--pitch', 4):.1f} {yaw:.1f} 0")
    for k in range(steps):
        turn = 360.0 * k / steps
        # the bot copies our yaw (looking at it); +180 turns it to face us, then the turntable step
        print(f"bot_mimic_yaw_offset {(180 + turn) % 360:.1f}")
        print(f"@wait {settle}")
        cast = opt("--cast", "", cast=str)
        if cast:
            key, frames, fps = cast.split(":")
            print(f"@key {key}")
            print(f"@burst {tag}_{int(turn):03d}_{key} {frames} {fps}")
        else:
            print(f"@shot {tag}_{int(turn):03d}")
    if "--keep" not in a:
        print("bot_mimic 0")
        print("citadel_camera_overrides_enabled 0")
        print("citadel_hud_visible 1")


if __name__ == "__main__":
    main(sys.argv[1:])
