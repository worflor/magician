"""Write a console.py scenario that walks the player around a target and captures it from every side.

    python -I orbit.py --target 1494 -1196 0 --radius 170 --steps 8 --height 60 --pitch 8 --tag idle > orbit.txt
    python -I console.py --out <run dir> --script orbit.txt

Deadlock's camera sits behind and over the player's right shoulder, so the player stands on the ring facing
the target and the camera frames the target past the player's shoulder. setpos/setang need sv_cheats 1.
Captures are named <tag>_<deg>.png; 0 deg is the target's +X side. Pass --face to also aim the shot down the
ring at the target's head (pitch from the eye height).
"""
import math
import sys


def main(a):
    def opt(name, default, n=1, cast=float):
        if name not in a:
            return default
        i = a.index(name)
        v = [cast(x) for x in a[i + 1:i + 1 + n]]
        return v if n > 1 else v[0]

    tx, ty, tz = opt("--target", [0, 0, 0], 3)
    radius = opt("--radius", 170)
    steps = int(opt("--steps", 8))
    height = opt("--height", 60)     # player origin height above the target's feet
    pitch = opt("--pitch", 8)
    tag = opt("--tag", "orbit", cast=str)
    settle = opt("--settle", 0.8)
    start = opt("--start", 0)
    print("# generated by orbit.py")
    print("sv_cheats 1")
    print("citadel_hud_visible 0")
    if "--self" in a:
        # Inspect your own hero: citadel_camera_overrides put the camera <dist> in front of the player looking
        # back (positive x offset), so turning the player with setang orbits the camera around them.
        dist = opt("--dist", 160)
        fov = opt("--fov", 0)
        print("citadel_camera_overrides_enabled 1")
        print(f"citadel_camera_override_x_offset {dist}")
        print(f"citadel_camera_override_y_offset {opt('--side', 0)}")
        print(f"citadel_camera_override_z_offset {opt('--up', 0)}")
        if fov:
            print(f"citadel_camera_override_fov {fov}")
        print(f"setpos {tx:.1f} {ty:.1f} {tz:.1f}")
        for k in range(steps):
            yaw = (start + 360.0 * k / steps) % 360
            print(f"setang {pitch:.1f} {yaw:.1f} 0")
            print(f"@wait {settle}")
            print(f"@shot {tag}_{int(round(yaw)):03d}")
        print("citadel_camera_overrides_enabled 0")
        print("citadel_hud_visible 1")
        return
    for k in range(steps):
        deg = (start + 360.0 * k / steps) % 360
        r = math.radians(deg)
        px, py = tx + radius * math.cos(r), ty + radius * math.sin(r)
        yaw = (deg + 180) % 360
        print(f"setpos {px:.1f} {py:.1f} {tz + height:.1f};setang {pitch:.1f} {yaw:.1f} 0")
        print(f"@wait {settle}")
        print(f"@shot {tag}_{int(round(deg)):03d}")
    print("citadel_hud_visible 1")


if __name__ == "__main__":
    main(sys.argv[1:])
