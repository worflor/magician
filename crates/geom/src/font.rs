/// The glyph's rows (top first) as 5-bit masks, padded to 9 rows.
pub fn rows(c: char) -> [u8; GLYPH_H] {
    let art = GLYPHS.iter().find(|(k, _)| *k == c).map(|(_, a)| *a).unwrap_or(MISSING);
    let mut out = [0u8; GLYPH_H];
    for (r, row) in art.split('/').enumerate().take(GLYPH_H) {
        for (x, ch) in row.chars().enumerate().take(GLYPH_W) {
            if ch == '#' {
                out[r] |= 1 << (GLYPH_W - 1 - x);
            }
        }
    }
    out
}

pub fn text_width(s: &str, scale: usize) -> usize {
    let n = s.chars().count();
    if n == 0 {
        0
    } else {
        (n * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP) * scale
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn glyphs_parse() {
        assert_eq!(GLYPHS.len(), 94);
        assert_eq!(rows('I')[0], 0b11111);
        assert_eq!(rows('p')[8], 0b10000, "p has a descender");
        assert_eq!(rows('\u{1}')[0], 0b11111, "missing glyph is a box");
        assert_eq!(text_width("ab", 2), 22);
    }
}
